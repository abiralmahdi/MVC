def slug(text):
    return re.sub(r'[^a-z0-9]+', '_', text.lower()).strip('_')


def fields_for(spec, definitions):
    if spec.get('fields'):
        return list(spec['fields'])
    if spec['type'] == 'Electricity Meter':
        return {'knx': KNX_ELECTRIC_FIELDS, 'mbus': MBUS_ELECTRIC_FIELDS, 'dali': DALI_ELECTRIC_FIELDS}.get(
            spec['protocol'], ELECTRIC_FIELDS)
    return list(definitions[spec['type']])


def _knx_dpt(field):
    if field in ('Energy', 'Total Active Power'):
        return '13.013', 1.0
    if field == 'Total Reactive Power':
        return '13.015', 1.0
    if field.startswith('Voltage') or 'Voltage' in field:
        return '14.027', 1.0
    if field.startswith('Current') or 'Current' in field:
        return '14.019', 1.0
    if field.startswith('Active Power'):
        return '14.056', 0.001          # W -> kW
    if field == 'Power Factor':
        return '14.057', 1.0
    if field == 'Line Frequency':
        return '14.033', 1.0
    if field == 'Temperature':
        return '9.001', 1.0
    if field == 'Humidity':
        return '9.007', 1.0
    if field == 'CO2 Level':
        return '9.008', 1.0
    if field == 'Pressure':
        return '9.006', 0.00001         # Pa -> bar
    return '14.056', 1.0


def build_device(spec, site_net, index, device_no, mbus_address, dali_address, knx_main):
    """Return (host, connection, mapping) for a simulated device."""
    protocol = spec['protocol']
    fields = spec['_fields']
    net = site_net
    if protocol == 'modbus':
        if spec['type'] == 'Electricity Meter':
            mapping = {f: {'fc': 3, 'address': ELECTRIC_REGISTERS[f],
                           'type': 'float64' if ELECTRIC_REGISTERS[f] >= 800 else 'float32', 'scale': 1.0} for f in fields}
        else:
            mapping = {f: {'fc': 4, 'address': 3000 + 2 * i, 'type': 'float32', 'scale': 1.0} for i, f in enumerate(fields)}
        return f'{net}.{index}', {'port': 502, 'unit_id': 1 + device_no % 4, 'timeout': 2.0}, mapping
    if protocol == 'opcua':
        tag = re.sub(r'[^A-Za-z0-9]', '', spec['name'])
        mapping = {f: {'node': f"ns=1;s=t|{tag}_{re.sub(r'[^A-Za-z0-9]', '', f)}", 'scale': 1.0} for f in fields}
        return f"{net}.{GATEWAYS['opcua']}", {'port': 4862, 'path': '', 'username': '', 'password': '', 'timeout': 3.0}, mapping
    if protocol == 'bacnet':
        mapping = {}
        for i, f in enumerate(fields):
            counter = f in COUNTERS
            mapping[f] = {'object_type': 'analog-value' if counter else 'analog-input',
                          'instance': (101 + i) if counter else (1 + i), 'property': 'present-value', 'scale': 1.0}
        return (f'{net}.{index}', {'port': 47808, 'device_instance': 10000 + index * 10, 'network': None, 'mac': None,
                                   'timeout': 3.0}, mapping)
    if protocol == 'knx':
        mapping = {}
        for i, f in enumerate(fields):
            dpt, scale = _knx_dpt(f)
            mapping[f] = {'group_address': f'{knx_main}/{device_no % 8}/{i + 1}', 'dpt': dpt, 'scale': scale}
        return (f"{net}.{GATEWAYS['knx']}", {'connection_type': 'tunneling', 'port': 3671, 'individual_address': '',
                                               'timeout': 3.0}, mapping)
    if protocol == 'dali':
        values = {'Active Power L1': ('active_power', 0.001), 'Total Active Power': ('active_energy', 0.001),
                  'Energy': ('active_energy', 0.001)}
        mapping = {f: {'address': dali_address, 'value': values[f][0], 'scale': values[f][1]} for f in fields}
        return f"{net}.{GATEWAYS['dali']}", {'port': 55825, 'timeout': 3.0}, mapping
    if protocol == 'mbus':
        scales = {'Energy': 0.001, 'Total Active Power': 0.001}   # meters report Wh
        mapping = {f: {'record': i, 'scale': scales.get(f, 1.0)} for i, f in enumerate(fields)}
        return (f"{net}.{GATEWAYS['mbus']}", {'transport': 'tcp', 'port': 10001, 'baudrate': 2400, 'address_mode': 'primary',
                                                'primary_address': mbus_address, 'timeout': 3.0}, mapping)
    if protocol == 'mqtt':
        site = slug(spec['_site'])
        mapping = {f: {'topic': f"{site}/{slug(spec['name'])}/telemetry", 'json_path': f'values.{slug(f)}', 'scale': 1.0}
                   for f in fields}
        return (f"{net}.{GATEWAYS['mqtt']}", {'port': 1883, 'tls': False, 'username': 'marksvision', 'password': 'demo-broker-pass',
                                                'client_id': '', 'wait': 5.0, 'max_age': 900}, mapping)
    raise ValueError(protocol)
